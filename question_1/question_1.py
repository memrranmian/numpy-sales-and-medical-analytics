import numpy as np

# Setting a fixed seed so when the professor runs this, random numbers stay predictable and consistent
np.random.seed(42)

print("=" * 70)
print("QUESTION 1: E-COMMERCE SALES AND INVENTORY ANALYTICS SYSTEM")
print("=" * 70)

# ------------------------------------------------------------------------------
# PART A: Array Creation and Initialization
# ------------------------------------------------------------------------------
print("\n>>> PART A: Array Creation and Initialization")

# A1. Create a 2D NumPy array containing the quantities sold for 5 products across 4 branches.
# Rows = 5 products (Product 0 to Product 4)
# Columns = 4 branches (Branch 0 to Branch 3)
# Let's write realistic daily sold quantities.
sales_quantity = np.array([
    [15, 20, 10, 25],  # Product 0
    [30, 12, 18, 22],  # Product 1
    [8,  15, 5,  12],  # Product 2
    [40, 25, 10, 15],  # Product 3 (total = 90 sold, so 100 - 90 = 10 units remaining, which is < 20!)
    [10, 8,  14, 16]   # Product 4
])
print("\nA1. Sales Quantity Array (Shape: 5 products x 4 branches):")
print(sales_quantity)

# A2. Create a 1D NumPy array containing the selling price of each product.
# 5 products, so 5 prices in Pakistani Rupees (PKR / Rs.)
# To make later conditions meaningful (e.g. products exceeding Rs. 50,000 revenue or price > 5,000),
# we choose appropriate product prices.
product_prices = np.array([1200.0, 3500.0, 7500.0, 800.0, 6200.0])
print("\nA2. Product Selling Prices (1D array for 5 products):")
print(product_prices)

# A3. Create an inventory array using np.full() or np.ones() to represent initial stock of each product.
# Let's say initial stock for each product was set to 100 units across the warehouse using np.full()
initial_stock = np.full(5, 100, dtype=int)
print("\nA3. Initial Stock Inventory Array (using np.full):")
print(initial_stock)

# A4. Use np.random.randint() to generate sample sales data for another day.
# Random quantities sold for 5 products across 4 branches, say between 5 and 50 units.
day2_sales_quantity = np.random.randint(5, 50, size=(5, 4))
print("\nA4. Sample Sales Data for Day 2 (Generated via np.random.randint):")
print(day2_sales_quantity)


# ------------------------------------------------------------------------------
# PART B: Sales Revenue Analysis
# ------------------------------------------------------------------------------
print("\n" + "=" * 70)
print(">>> PART B: Sales Revenue Analysis")

# B1. Use broadcasting to multiply sales quantity array by product price array to calculate branch-wise product revenue.
# sales_quantity is (5, 4). product_prices is (5,).
# If we simply multiply (5, 4) * (5,), numpy throws an error because trailing dimension 4 != 5!
# In lecture, sir explained we need to reshape product_prices to (5, 1) using reshape(5, 1) or np.newaxis.
# Then (5, 4) * (5, 1) broadcasts nicely across columns!
branch_product_revenue = sales_quantity * product_prices.reshape(5, 1)
print("\nB1. Branch-wise Product Revenue Matrix (PKR):")
print(branch_product_revenue)

# B2. Calculate total revenue generated by each branch.
# Branches are along columns, so to sum down each column, we sum over axis=0.
branch_total_revenue = np.sum(branch_product_revenue, axis=0)
print("\nB2. Total Revenue Generated by Each Branch (Branches 0 to 3):")
for b_idx, rev in enumerate(branch_total_revenue):
    print(f"   Branch {b_idx}: Rs. {rev:,.2f}")

# B3. Calculate total revenue generated by each product.
# Products are rows, so to sum across all branches for each product, we sum over axis=1.
product_total_revenue = np.sum(branch_product_revenue, axis=1)
print("\nB3. Total Revenue Generated by Each Product (Products 0 to 4):")
for p_idx, rev in enumerate(product_total_revenue):
    print(f"   Product {p_idx}: Rs. {rev:,.2f}")

# B4. Identify the branch generating the highest revenue.
best_branch_idx = np.argmax(branch_total_revenue)
print(f"\nB4. Highest Revenue Branch: Branch {best_branch_idx} with Rs. {branch_total_revenue[best_branch_idx]:,.2f}")

# B5. Use appropriate aggregate functions to calculate the company's total sales revenue.
company_total_revenue = np.sum(branch_product_revenue)
print(f"\nB5. Company Total Sales Revenue: Rs. {company_total_revenue:,.2f}")


# ------------------------------------------------------------------------------
# PART C: Searching and Boolean Indexing
# ------------------------------------------------------------------------------
print("\n" + "=" * 70)
print(">>> PART C: Searching and Boolean Indexing")

# C1. Identify products whose total sales revenue exceeds Rs. 50,000.
# We create a boolean mask on product_total_revenue.
rev_above_50k_mask = product_total_revenue > 50000
products_above_50k = np.where(rev_above_50k_mask)[0]
print(f"\nC1. Products with Total Revenue > Rs. 50,000:")
print(f"   Boolean Mask: {rev_above_50k_mask}")
print(f"   Matching Product Indices: {products_above_50k}")
for p in products_above_50k:
    print(f"   - Product {p}: Total Revenue = Rs. {product_total_revenue[p]:,.2f}")

# C2. Identify branches where total revenue exceeds Rs. 100,000.
rev_above_100k_mask = branch_total_revenue > 100000
branches_above_100k = np.where(rev_above_100k_mask)[0]
print(f"\nC2. Branches with Total Revenue > Rs. 100,000:")
print(f"   Boolean Mask: {rev_above_100k_mask}")
print(f"   Matching Branch Indices: {branches_above_100k}")
for b in branches_above_100k:
    print(f"   - Branch {b}: Total Revenue = Rs. {branch_total_revenue[b]:,.2f}")

# C3. Use Boolean indexing to identify products with remaining stock below 20 units.
# First calculate total units sold for each product across all branches (sum axis=1).
total_units_sold = np.sum(sales_quantity, axis=1)
remaining_stock = initial_stock - total_units_sold
print(f"\n   Total Units Sold per Product: {total_units_sold}")
print(f"   Remaining Stock per Product:  {remaining_stock}")

low_stock_mask = remaining_stock < 20
low_stock_products = np.where(low_stock_mask)[0]
print(f"\nC3. Products with Remaining Stock < 20 Units (using Boolean indexing):")
print(f"   Boolean Mask: {low_stock_mask}")
print(f"   Remaining stock values filtered: {remaining_stock[low_stock_mask]}")
print(f"   Product indices with low stock: {low_stock_products}")

# C4. Use np.where() to locate products whose selling prices exceed Rs. 5,000.
expensive_products_idx = np.where(product_prices > 5000)[0]
print(f"\nC4. Products with Selling Price > Rs. 5,000 (located via np.where):")
print(f"   Product Indices: {expensive_products_idx}")
for p in expensive_products_idx:
    print(f"   - Product {p}: Price = Rs. {product_prices[p]:,.2f}")


# ------------------------------------------------------------------------------
# PART D: Inventory Updating and Array Manipulation
# ------------------------------------------------------------------------------
print("\n" + "=" * 70)
print(">>> PART D: Inventory Updating and Array Manipulation")

# D1. Update the inventory array by subtracting the total quantities sold.
# We do this directly: current_inventory = initial_stock - total_units_sold
current_inventory = initial_stock.copy()
current_inventory = current_inventory - total_units_sold
print(f"\nD1. Updated Inventory Array after subtracting total sales:")
print(f"   Original Stock: {initial_stock}")
print(f"   Deductions:     {total_units_sold}")
print(f"   Current Stock:  {current_inventory}")

# D2. Use np.append() to add a new product's stock information.
# Suppose product 5 is launched with initial stock of 80 units.
current_inventory = np.append(current_inventory, 80)
print(f"\nD2. Inventory after np.append() (New Product 5 added with 80 units):")
print(f"   Inventory: {current_inventory}")

# D3. Use np.insert() to insert a new product at a specified position.
# Suppose a new premium product is inserted at index 2 with 65 units.
current_inventory = np.insert(current_inventory, 2, 65)
print(f"\nD3. Inventory after np.insert() (Inserted 65 units at index 2):")
print(f"   Inventory: {current_inventory}")

# D4. Use np.delete() to remove a discontinued product.
# Suppose product at index 1 is discontinued, let's delete it.
current_inventory = np.delete(current_inventory, 1)
print(f"\nD4. Inventory after np.delete() (Removed discontinued product at index 1):")
print(f"   Inventory: {current_inventory}")

# D5. Identify products that need restocking based on the remaining stock quantity.
# Let's say restocking threshold is any stock <= 30 units.
# We can check against the actual remaining stock of our active 5 products:
restock_threshold = 30
need_restock_mask = remaining_stock <= restock_threshold
restock_products = np.where(need_restock_mask)[0]
print(f"\nD5. Products Requiring Restocking (Threshold <= {restock_threshold} units):")
for p in restock_products:
    print(f"   - Product {p}: Current Stock = {remaining_stock[p]} units (Restock Needed!)")


# ------------------------------------------------------------------------------
# PART E: Array Concatenation, Stacking, and Splitting
# ------------------------------------------------------------------------------
print("\n" + "=" * 70)
print(">>> PART E: Array Concatenation, Stacking, and Splitting")

# E1. Generate sales data for two consecutive days.
# Day 1 is our initial sales_quantity (5x4)
day1_sales = sales_quantity.copy()
# Day 2 was generated earlier or generated fresh (5x4)
day2_sales = day2_sales_quantity.copy()
print("\nE1. Sales Data for Day 1 (5x4):")
print(day1_sales)
print("\nSales Data for Day 2 (5x4):")
print(day2_sales)

# E2. Use np.concatenate() to combine sales data from both days.
# Concatenating along axis=0 gives 10 rows (5 products Day 1 + 5 products Day 2)
combined_concat = np.concatenate((day1_sales, day2_sales), axis=0)
print(f"\nE2. Combined Sales Data using np.concatenate (axis=0, shape: {combined_concat.shape}):")
print(combined_concat)

# E3. Use np.vstack() and np.hstack() to combine appropriate sales arrays.
# vstack stacks vertically (same as concatenate axis=0) -> (10, 4)
sales_vstacked = np.vstack((day1_sales, day2_sales))
print(f"\nE3. Vertical Stacking (np.vstack) - Stacked Days by Row (Shape: {sales_vstacked.shape}):")
print(sales_vstacked)

# hstack stacks horizontally -> (5, 8) represents 5 products across 8 branch-day slots
sales_hstacked = np.hstack((day1_sales, day2_sales))
print(f"\nHorizontal Stacking (np.hstack) - Stacked Days by Column (Shape: {sales_hstacked.shape}):")
print(sales_hstacked)

# E4. Use np.split() to divide the combined sales data into separate daily sales records.
# We split combined_concat (10, 4) back into 2 arrays along axis=0.
split_days = np.split(combined_concat, 2, axis=0)
print("\nE4. Splitting combined sales data back using np.split():")
print("   Recovered Day 1 Sales Data:")
print(split_days[0])
print("   Recovered Day 2 Sales Data:")
print(split_days[1])
# Double check if recovered matches original Day 1
print(f"   Does split Day 1 exactly match original Day 1? {np.array_equal(split_days[0], day1_sales)}")


# ------------------------------------------------------------------------------
# PART F: Sorting and Data Processing
# ------------------------------------------------------------------------------
print("\n" + "=" * 70)
print(">>> PART F: Sorting and Data Processing")

# F1. Sort product-wise revenue in ascending and descending order.
sorted_rev_asc = np.sort(product_total_revenue)
# In python numpy, descending can be done by flipping with [::-1]
sorted_rev_desc = np.sort(product_total_revenue)[::-1]
print(f"\nF1. Product-wise Revenue:")
print(f"   Original:   {product_total_revenue}")
print(f"   Ascending:  {sorted_rev_asc}")
print(f"   Descending: {sorted_rev_desc}")

# F2. Use np.argsort() to identify product positions according to revenue.
# argsort returns indices that would sort the array
sorted_indices_asc = np.argsort(product_total_revenue)
sorted_indices_desc = np.argsort(product_total_revenue)[::-1]
print(f"\nF2. Product Indices Sorted by Revenue:")
print(f"   Lowest to Highest (Ascending):  {sorted_indices_asc}")
print(f"   Highest to Lowest (Descending): {sorted_indices_desc}")

# F3. Use np.max(), np.min(), and np.mean() to summarize sales performance.
max_product_rev = np.max(product_total_revenue)
min_product_rev = np.min(product_total_revenue)
mean_product_rev = np.mean(product_total_revenue)
print(f"\nF3. Sales Performance Summary (Product Revenue):")
print(f"   Maximum Product Revenue: Rs. {max_product_rev:,.2f}")
print(f"   Minimum Product Revenue: Rs. {min_product_rev:,.2f}")
print(f"   Average Product Revenue: Rs. {mean_product_rev:,.2f}")

# F4. Iterate through the sales array to display branch-wise information.
# Let's iterate over each branch (columns) and print quantities sold for each product.
print("\nF4. Iterating through the Sales Array to Display Branch-wise Information:")
num_products, num_branches = sales_quantity.shape
for b in range(num_branches):
    print(f"\n   --- Branch {b} Summary ---")
    branch_qty = sales_quantity[:, b]
    branch_rev = branch_product_revenue[:, b]
    for p in range(num_products):
        print(f"      Product {p}: Sold = {branch_qty[p]} units | Revenue = Rs. {branch_rev[p]:,.2f}")
    print(f"      Total Branch {b} Revenue: Rs. {np.sum(branch_rev):,.2f}")


